'use strict';
const assert=require('node:assert/strict');
const core=require('../main/userSleepState');
const owner='wake-trace-fixture', base=Date.parse('2026-11-12T00:00:00Z');
const event=(id,kind,source,at,extra={})=>({version:1,id,owner,kind,source,at,recordedAt:at,deviceId:'fixture-device',...extra});
const sleep=event('sleep-1','sleepConfirmed','manual',base);
const activity=event('presence-1','activity','human-input',base+8*3600000);
const ai=event('agent-1','activity','codex-agent',base+8*3600000+60000);
const wake=event('wake-1','wakeConfirmed','manual',base+8*3600000+120000);
const result=core.reduceConfirmed([sleep,activity,ai,wake],{owner,now:wake.at+60000,minutes:120});
assert.equal(result.state,'awake');
assert.equal(result.shouldLock,true);
assert.deepEqual(result.decisionTrace.decisiveEventIds,['wake-1','sleep-1']);
const activityTrace=result.decisionTrace.evaluatedSignals.find(row=>row.eventId==='presence-1');
assert.equal(activityTrace.effect,'excluded-by-confirmed-policy');
assert.equal(activityTrace.origin,'human-or-user-data');
assert.equal(activityTrace.accepted,false);
const aiTrace=result.decisionTrace.evaluatedSignals.find(row=>row.eventId==='agent-1');
assert.equal(aiTrace.effect,'excluded-by-confirmed-policy');
assert.equal(aiTrace.origin,'ai-or-agent');
assert.equal(result.decisionTrace.outcome.shouldLock,true);
assert.deepEqual(result.decisionTrace.decisiveContributors.map(row=>row.eventId),['sleep-1','wake-1']);
console.log('wake-decision-trace-smoke.js: passed (human presence and AI activity separated; confirmed wake and lock deadline attributed)');
